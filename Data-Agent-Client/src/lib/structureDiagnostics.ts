export function structureDiagnosticText(diagnostic: StructureDiagnostic, t: Translator): string {
  const key = DIAGNOSTIC_KEYS[diagnostic.code];
  if (!key) return diagnostic.code;
  const [name = '', detail = '', extra = ''] = diagnostic.args ?? [];
  return t(key, { name, detail, extra });
}
